#!/usr/bin/env python3
"""Verify the curated, reproducible Sky VeLor source-release archive.

The release workflow builds this archive with ``git archive`` rather than copying a
working tree.  That keeps generated Forge output, previous distribution artifacts,
Git internals, IDE state and local credentials out of the source delivery.

Usage: python3 tools/verify_source_zip.py <source-zip> --version Beta-0.10.8.9.3v
"""

from __future__ import print_function

import argparse
import os
import sys
import zipfile


class Results(object):
    def __init__(self):
        self.passed = 0
        self.failed = 0

    def check(self, okay, message):
        if okay:
            self.passed += 1
            print("  PASS " + message)
        else:
            self.failed += 1
            print("  FAIL " + message)


def read_text(archive, name):
    try:
        return archive.read(name).decode('utf-8')
    except (KeyError, UnicodeDecodeError):
        return ''


def is_forbidden(relative_name):
    parts = [part.lower() for part in relative_name.split('/') if part]
    forbidden_directories = set((
        '.git', '.gradle', '.idea', 'build', 'dist', 'out', 'target', 'node_modules',
        'run', 'logs', 'crash-reports', 'ci-evidence'
    ))
    if any(part in forbidden_directories for part in parts):
        return True

    lower = relative_name.lower()
    forbidden_suffixes = ('.class', '.iml', '.pyc', '.zip', '.tar', '.gz', '.7z', '.nef')
    # Do not let retired external-project archives/notices re-enter a curated source release under a text extension.
    forbidden_name_fragments = ('better' + '-nef', 'not' + 'enoughfakepixel')
    if lower.endswith(forbidden_suffixes) or any(fragment in lower for fragment in forbidden_name_fragments):
        return True
    if lower.endswith('.jar') and relative_name != 'gradle/wrapper/gradle-wrapper.jar':
        return True

    base = parts[-1] if parts else ''
    if base == '.env' or base.startswith('.env.') or base.endswith('.pem') or base.endswith('.key'):
        return True
    if 'credential' in base or 'secret' in base:
        return True
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', help='source ZIP generated by git archive')
    parser.add_argument('--version', required=True, help='display release version, e.g. Beta-0.10.8.9.3v')
    args = parser.parse_args()

    expected_name = 'SkyVeLor-1.8.9-' + args.version + '-source.zip'
    root = expected_name[:-4] + '/'
    results = Results()
    results.check(os.path.basename(args.archive) == expected_name,
                  'archive file name is ' + expected_name)

    try:
        archive = zipfile.ZipFile(args.archive, 'r')
    except (IOError, OSError, zipfile.BadZipfile) as exc:
        print('source ZIP verification: passed 0, failed 1')
        print('  FAIL cannot read source ZIP: ' + str(exc))
        return 1

    try:
        names = archive.namelist()
        relative_names = []
        safe_names = True
        for name in names:
            if not name.startswith(root):
                safe_names = False
                continue
            relative = name[len(root):]
            if relative and (relative.startswith('/') or '..' in relative.split('/') or '\\' in relative):
                safe_names = False
            if relative:
                relative_names.append(relative)

        results.check(len(names) > 0 and all(name.startswith(root) for name in names),
                      'every entry has the required root prefix')
        results.check(safe_names, 'archive paths are relative and traversal-free')
        results.check(len(relative_names) == len(set(relative_names)), 'archive contains no duplicate paths')

        required = (
            '.github/workflows/build.yml', '.gitignore', 'CHANGELOG.md', 'LICENSE', 'README.md',
            'build.gradle', 'settings.gradle', 'gradlew', 'gradlew.bat',
            'gradle/wrapper/gradle-wrapper.jar', 'gradle/wrapper/gradle-wrapper.properties',
            'src/main/java/com/arena/pekaclient/PekaVersion.java', 'src/main/resources/mcmod.info',
            'tests/run-tests.sh', 'tests/run-tests.bat', 'tools/verify_release_jar.py',
            'tools/verify_source_zip.py', 'docs/FEATURE-SETTINGS-EDITOR.md'
        )
        available = set(relative_names)
        missing = [name for name in required if name not in available]
        results.check(not missing, 'required source, build, wrapper, test, tool, CI, docs and license files exist'
                      + ('' if not missing else ': ' + ', '.join(missing)))

        required_prefixes = ('src/main/', 'tests/', 'tools/', 'docs/', '.github/')
        absent_prefixes = [prefix for prefix in required_prefixes
                           if not any(name.startswith(prefix) for name in relative_names)]
        results.check(not absent_prefixes, 'required source tree sections are non-empty'
                      + ('' if not absent_prefixes else ': ' + ', '.join(absent_prefixes)))

        forbidden = [name for name in relative_names if is_forbidden(name)]
        results.check(not forbidden,
                      'no build artifacts, Git state, IDE files, release archives or secret-looking files are present'
                      + ('' if not forbidden else ': ' + ', '.join(forbidden[:12])))

        jars = [name for name in relative_names if name.lower().endswith('.jar')]
        results.check(jars == ['gradle/wrapper/gradle-wrapper.jar'],
                      'the Gradle wrapper is the only archived JAR'
                      + ('' if jars == ['gradle/wrapper/gradle-wrapper.jar'] else ': ' + ', '.join(jars)))

        version_source = read_text(archive, root + 'src/main/java/com/arena/pekaclient/PekaVersion.java')
        metadata = read_text(archive, root + 'src/main/resources/mcmod.info')
        results.check('NAME = "' + args.version + '"' in version_source,
                      'PekaVersion.NAME matches the archive version')
        results.check('Sky VeLor ' + args.version in metadata and '"version": "${version}"' in metadata,
                      'mcmod.info carries the matching display version and generated numeric version placeholder')
    finally:
        archive.close()

    print('source ZIP verification: passed {0}, failed {1}'.format(results.passed, results.failed))
    return 1 if results.failed else 0


if __name__ == '__main__':
    sys.exit(main())
