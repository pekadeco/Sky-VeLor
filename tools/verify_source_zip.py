#!/usr/bin/env python3
"""Verify the curated, reproducible The Sky's Lunaria Mod source-release archive."""
from __future__ import print_function

import argparse
import os
import sys
import zipfile


class Results(object):
    def __init__(self):
        self.passed = 0
        self.failed = 0

    def check(self, condition, message):
        if condition:
            self.passed += 1
            print("  ok   " + message)
        else:
            self.failed += 1
            print("  FAIL " + message)


def read_text(archive, name):
    return archive.read(name).decode("utf-8", "replace")


def forbidden(path):
    lower = path.lower()
    parts = lower.split("/")
    base = parts[-1]
    if any(part in (".git", "build", "dist", ".gradle", "node_modules", "__pycache__") for part in parts):
        return True
    if base.endswith((".class", ".pyc", ".pyo", ".iml", ".log", ".bak", ".tmp")):
        return True
    if base.endswith((".zip", ".tar", ".gz", ".7z")):
        return True
    if base.endswith(".jar") and path != "gradle/wrapper/gradle-wrapper.jar":
        return True
    if base == ".env" or base.startswith(".env.") or base.endswith((".pem", ".key")):
        return True
    return "credential" in base or "secret" in base


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", help="source ZIP generated by git archive")
    parser.add_argument("--version", required=True, help="display release version, e.g. Beta-0.10.9.4v")
    args = parser.parse_args()

    expected_name = "Lunaria-Mod-1.8.9-" + args.version + "-source.zip"
    root = expected_name[:-4] + "/"
    result = Results()
    result.check(os.path.basename(args.archive) == expected_name, "archive file name is " + expected_name)

    try:
        archive = zipfile.ZipFile(args.archive, "r")
    except (IOError, OSError, zipfile.BadZipfile) as error:
        result.check(False, "source ZIP is readable: " + str(error))
        print("source ZIP verification: passed {0}, failed {1}".format(result.passed, result.failed))
        return 1

    try:
        names = archive.namelist()
        relative = []
        safe = True
        for name in names:
            if not name.startswith(root):
                safe = False
                continue
            child = name[len(root):]
            if child and (child.startswith("/") or ".." in child.split("/") or "\\" in child):
                safe = False
            if child:
                relative.append(child)
        available = set(relative)
        result.check(bool(names) and all(name.startswith(root) for name in names),
                     "every archive entry uses the Lunaria source root")
        result.check(safe, "archive paths are relative and traversal-free")
        result.check(len(relative) == len(available), "archive contains no duplicate paths")

        required = (
            ".github/workflows/build.yml", ".gitignore", "BUILD-VERIFICATION.md", "CHANGELOG.md",
            "DIAGNOSTIC_REPORT.md", "LICENSE", "README.md", "THIRD-PARTY-NOTICES.md", "NOTICE.md",
            "VERIFICATION.md", "privacy.md", "build.gradle", "settings.gradle",
            "gradlew", "gradlew.bat", "gradle/wrapper/gradle-wrapper.jar",
            "gradle/wrapper/gradle-wrapper.properties", "docs/FEATURE-SETTINGS-EDITOR.md",
            "docs/CONFIGURATION-MIGRATION.md", "docs/LOADING-SCREEN.md",
            "src/main/java/com/arena/pekaclient/PekaClientMod.java",
            "src/main/java/com/arena/pekaclient/PekaVersion.java",
            "src/main/java/com/arena/pekaclient/config/AppleSettings.java",
            "src/main/java/com/arena/pekaclient/config/FontSettings.java",
            "src/main/java/com/arena/pekaclient/config/KeybindMigration.java",
            "src/main/java/com/arena/pekaclient/command/SvCommand.java",
            "src/main/java/com/arena/pekaclient/command/SvDungeonCommand.java",
            "src/main/java/com/arena/pekaclient/itemlockswap/ItemLockSwapController.java",
            "src/main/java/com/arena/pekaclient/dungeon/DungeonMapOverlay.java",
            "src/main/java/com/arena/pekaclient/gui/DungeonHudEditorScreen.java",
            "src/main/java/com/arena/pekaclient/gui/ChatEditorScreen.java",
            "src/main/java/com/arena/pekaclient/gui/LunariaArtwork.java",
            "src/main/java/com/arena/pekaclient/gui/LunariaDownloadingTerrainScreen.java",
            "src/main/java/com/arena/pekaclient/render/ExternalFontLocations.java",
            "src/main/java/com/arena/pekaclient/assist/dungeon/DungeonScoreTracker.java",
            "src/main/java/com/arena/pekaclient/assist/dungeon/RoomClearAlertController.java",
            "src/main/java/com/arena/pekaclient/assist/dungeon/DungeonChestCloser.java",
            "src/main/java/com/arena/pekaclient/assist/visual/DeadMobRenderFilter.java",
            "src/main/java/com/arena/pekaclient/assist/visual/AspectTeleportTransitionRenderer.java",
            "src/main/resources/mcmod.info", "src/main/resources/mixins.lunaria.json",
            "src/main/resources/assets/lunaria/lang/en_US.lang",
            "src/main/resources/assets/lunaria/textures/gui/lunaria_loading_background.jpg",
            "src/main/resources/assets/lunaria/textures/gui/lunaria_logo.png",
            "tests/run-tests.sh", "tests/run-tests.bat",
            "tests/com/arena/pekaclient/config/AppleSettingsTests.java",
            "tests/com/arena/pekaclient/config/KeybindMigrationTests.java",
            "tests/com/arena/pekaclient/feature/inventory/SlotLockStoreTests.java",
            "tests/com/arena/pekaclient/render/ExternalFontLocationsTests.java",
            "tests/com/arena/pekaclient/gui/ChatQolLayoutTests.java",
            "tests/com/arena/pekaclient/gui/ReleaseClaimsTests.java",
            "tools/verify_release_jar.py", "tools/verify_source_zip.py",
        )
        missing = [name for name in required if name not in available]
        result.check(not missing, "required source, tests, resources, documentation, CI and verifiers are present"
                     + ("" if not missing else ": " + ", ".join(missing)))

        prefixes = ("src/main/", "tests/", "tools/", "docs/", ".github/")
        absent = [prefix for prefix in prefixes if not any(name.startswith(prefix) for name in relative)]
        result.check(not absent, "required source tree sections are non-empty"
                     + ("" if not absent else ": " + ", ".join(absent)))
        result.check(sum(1 for name in relative if name.startswith("tests/") and name.endswith("Tests.java")) >= 100,
                     "source archive retains a broad standalone regression suite")

        blocked = [name for name in relative if forbidden(name)]
        result.check(not blocked, "no build products, reference ZIPs, Git state, IDE files or secret-looking files are archived"
                     + ("" if not blocked else ": " + ", ".join(blocked[:12])))
        jars = [name for name in relative if name.lower().endswith(".jar")]
        result.check(jars == ["gradle/wrapper/gradle-wrapper.jar"], "Gradle wrapper is the only archived JAR"
                     + ("" if jars == ["gradle/wrapper/gradle-wrapper.jar"] else ": " + ", ".join(jars)))
        result.check(not any(name.startswith("assets/pekaclient/") or name.startswith("src/main/resources/assets/pekaclient/")
                             for name in relative),
                     "source resources use only the Lunaria asset namespace")

        version = read_text(archive, root + "src/main/java/com/arena/pekaclient/PekaVersion.java")
        metadata = read_text(archive, root + "src/main/resources/mcmod.info")
        entry = read_text(archive, root + "src/main/java/com/arena/pekaclient/PekaClientMod.java")
        settings = read_text(archive, root + "src/main/java/com/arena/pekaclient/config/AppleSettings.java")
        commands = read_text(archive, root + "src/main/java/com/arena/pekaclient/command/SvCommand.java")
        artwork = read_text(archive, root + "src/main/java/com/arena/pekaclient/gui/LunariaArtwork.java")
        workflow = read_text(archive, root + ".github/workflows/build.yml")
        result.check('NAME = "' + args.version + '"' in version and "The Sky's Lunaria Mod" in version,
                     "PekaVersion carries the Lunaria title and requested display version")
        result.check('"modid": "lunaria"' in metadata and '"name": "The Sky\'s Lunaria Mod"' in metadata
                     and '"version": "${version}"' in metadata,
                     "mcmod metadata uses Lunaria identity and generated numeric version")
        result.check("lunaria.properties" in settings and "skyvelor.properties" in settings
                     and "FontSettings" in settings,
                     "settings source preserves Lunaria writes and legacy-read configuration migration")
        result.check('"lunaria"' in commands and '"sv"' in commands and '"velor"' in commands,
                     "command source exposes canonical /lunaria and both compatibility aliases")
        result.check("drawScaledCustomSizeModalRect" in artwork and "GL_NEAREST" in artwork,
                     "loading artwork source uses cropped aspect-fill draw and pixel-sharp logo filtering")
        result.check("LunariaDownloadingTerrainScreen" in entry and "DungeonChestCloser" in entry,
                     "entry point retains terrain overlay and required current features")
        result.check("JAR_NAME=Lunaria-Mod-1.8.9-" in workflow
                     and "SOURCE_ZIP_NAME=Lunaria-Mod-1.8.9-" in workflow
                     and "gh release" not in workflow,
                     "CI produces Lunaria-named branch artifacts without creating GitHub Releases")
    except (KeyError, IOError, OSError, zipfile.BadZipfile) as error:
        result.check(False, "required source archive content is readable: " + str(error))
    finally:
        archive.close()

    print("source ZIP verification: passed {0}, failed {1}".format(result.passed, result.failed))
    return 1 if result.failed else 0


if __name__ == "__main__":
    sys.exit(main())
